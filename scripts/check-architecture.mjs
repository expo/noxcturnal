import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const failures = [];

function sourceFiles(directory, extension) {
  const output = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) output.push(...sourceFiles(filename, extension));
    else if (entry.name.endsWith(extension)) output.push(filename);
  }
  return output;
}

const importPattern = /\b(?:import|export)\s+(?:type\s+)?(?:[^'"]*?\s+from\s+)?['"]([^'"]+)['"]/g;
const typescriptGraph = new Map();
for (const filename of sourceFiles(path.join(root, 'js'), '.ts')) {
  const relative = path.relative(root, filename);
  const source = fs.readFileSync(filename, 'utf8');
  const dependencies = [];
  for (const match of source.matchAll(importPattern)) {
    const specifier = match[1];
    if (specifier.startsWith('.')) {
      const resolved = path.resolve(path.dirname(filename), specifier.replace(/\.js$/, '.ts'));
      if (fs.existsSync(resolved)) dependencies.push(path.relative(root, resolved));
    }
    if (relative !== 'js/index.ts' && /(?:^|\/)index\.js$/.test(specifier))
      failures.push(`${relative}: internal modules must not import the package composition root`);
    if (
      relative.startsWith('js/protocol/') &&
      /(?:^|\/)(?:runtime|pipeline)(?:\/|\.js$)/.test(specifier)
    )
      failures.push(`${relative}: protocol must not depend on runtime or pipeline`);
    if (relative.startsWith('js/pipeline/') && /(?:^|\/)runtime(?:\/|\.js$)/.test(specifier))
      failures.push(`${relative}: pipeline must not depend on runtime`);
    if (
      relative.startsWith('js/contracts/') &&
      /(?:^|\/)(?:runtime|pipeline)(?:\/|\.js$)/.test(specifier)
    )
      failures.push(`${relative}: contracts must not depend on runtime or pipeline`);
  }
  typescriptGraph.set(relative, dependencies);
}

const visiting = new Set();
const visited = new Set();
function visitTypescriptModule(module, ancestry) {
  if (visiting.has(module)) {
    const start = ancestry.indexOf(module);
    failures.push(
      `TypeScript dependency cycle: ${[...ancestry.slice(start), module].join(' -> ')}`,
    );
    return;
  }
  if (visited.has(module)) return;
  visiting.add(module);
  for (const dependency of typescriptGraph.get(module) ?? [])
    visitTypescriptModule(dependency, [...ancestry, module]);
  visiting.delete(module);
  visited.add(module);
}
for (const module of typescriptGraph.keys()) visitTypescriptModule(module, []);

const rustProtocol = path.join(root, 'src/protocol');
if (fs.existsSync(rustProtocol)) {
  for (const filename of sourceFiles(rustProtocol, '.rs')) {
    if (/\b(?:crate::)?engine(?:::|\b)/.test(fs.readFileSync(filename, 'utf8')))
      failures.push(`${path.relative(root, filename)}: protocol must not depend on engine`);
  }
}

const helperMaterializer = fs.readFileSync(path.join(root, 'src/preflight/helpers.rs'), 'utf8');
if (/\bconst\s+INLINE_[A-Z_]+/.test(helperMaterializer)) {
  failures.push(
    'src/preflight/helpers.rs: inline Babel helper bodies must come from generated/inline_helpers.rs',
  );
}
for (const filename of sourceFiles(path.join(root, 'src/preflight'), '.rs')) {
  const source = fs.readFileSync(filename, 'utf8');
  if (/\bconst\s+[A-Z][A-Z_]*HELPERS?\s*:\s*&str/.test(source)) {
    failures.push(
      `${path.relative(root, filename)}: handwritten helper bodies must be generated from @babel/runtime`,
    );
  }
}
const generatedHelpers = fs.readFileSync(
  path.join(root, 'src/generated/inline_helpers.rs'),
  'utf8',
);
if (!generatedHelpers.startsWith('// @generated by scripts/generate-inline-helpers.mjs')) {
  failures.push('src/generated/inline_helpers.rs: missing runtime-derived generated marker');
}

for (const obsolete of [
  'js/native.ts',
  'js/generated-event-schema.ts',
  'js/protocol.ts',
  'js/visitors.ts',
  'src/engine.rs',
  'src/sourcemap.rs',
  'src/editor.rs',
  'src/function_map.rs',
  'src/generated_event_schema.rs',
  'src/retained_index.rs',
  'src/constant_eval.rs',
]) {
  if (fs.existsSync(path.join(root, obsolete)))
    failures.push(`${obsolete}: obsolete module path must not be restored`);
}

for (const obsolete of [
  'dist/native.js',
  'dist/native.d.ts',
  'dist/protocol.js',
  'dist/protocol.d.ts',
  'dist/visitors.js',
  'dist/visitors.d.ts',
  'dist/generated-event-schema.js',
  'dist/generated-event-schema.d.ts',
]) {
  if (fs.existsSync(path.join(root, obsolete)))
    failures.push(`${obsolete}: stale generated compatibility artifact must not be packaged`);
}

const declarationRoots = ['js', 'test', 'benchmark'];
const legacyAncestry =
  /\bancestry\s*:\s*(?:['"](?:parent|findParent|functionParent|programParent)['"]|[1-9]\d*)/g;
function hasLegacyVisitorAncestry(source) {
  for (const match of source.matchAll(legacyAncestry)) {
    const prefix = source.slice(Math.max(0, match.index - 80), match.index);
    if (!/\bsnapshot\s*\([^)]*$/.test(prefix)) return true;
  }
  return false;
}
for (const directory of declarationRoots) {
  for (const filename of sourceFiles(path.join(root, directory), '.ts')) {
    if (hasLegacyVisitorAncestry(fs.readFileSync(filename, 'utf8')))
      failures.push(
        `${path.relative(root, filename)}: legacy string/numeric ancestry declaration remains`,
      );
  }
}

const expoTransformer = path.resolve(
  root,
  '../expo/packages/@expo/metro-config/src/transform-worker/noxcturnal-transformer.ts',
);
if (fs.existsSync(expoTransformer)) {
  const source = fs.readFileSync(expoTransformer, 'utf8');
  if (hasLegacyVisitorAncestry(source))
    failures.push('Expo noxcturnal transformer: legacy ancestry declaration remains');
  const ancestorAliases = [];
  for (const match of source.matchAll(
    /\b(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*[^;\n]*(?:parentPath|findParent|getFunctionParent|getProgramParent)\b/g,
  ))
    ancestorAliases.push({ name: match[1], index: match.index });
  if (
    /\b(?:parentPath|findParent|getFunctionParent|getProgramParent)\b[^;\n]*\.sourceText\s*\(/.test(
      source,
    ) ||
    ancestorAliases.some(({ name, index }) =>
      new RegExp(`\\b${name}\\.sourceText\\s*\\(`).test(source.slice(index, index + 1200)),
    ) ||
    /findParent\s*\([^)]*sourceText\s*\(/s.test(source)
  )
    failures.push(
      'Expo noxcturnal transformer: sourceText() must not be called on ancestry-derived paths',
    );
}

if (failures.length > 0) {
  console.error(failures.join('\n'));
  process.exitCode = 1;
}
